function filterStudentsList(allStudents) {
    if (!Array.isArray(allStudents)) return [];
    const query = normalizeText(currentStudentSearchQuery || '');
    return allStudents.filter(student => {
        const matchesInterest = !activeInterestFilters || activeInterestFilters.length === 0 ||
            activeInterestFilters.every(filter => student.interests?.includes(filter));
        if (!matchesInterest) return false;

        if (!query) return true;

        const fullNameNorm = normalizeText(student.fullName || '');
        const preferredNameNorm = normalizeText(student.preferredName || '');
        const listNumStr = String(student.listNumber || '');

        return fullNameNorm.includes(query) || preferredNameNorm.includes(query) || listNumStr === query;
    });
}

