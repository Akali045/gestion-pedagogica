// File System Access API State
let currentFileHandle = null;
let hasUnsavedChanges = false;
let autoSaveTimeout = null;

function loadData() {
    // Attempt to recover legacy local storage data if present
    const saved = localStorage.getItem('pedagogicalData');
    if (saved) {
        appData = JSON.parse(saved);
        if (!appData.deletedItems) appData.deletedItems = [];
        hasUnsavedChanges = true;
        updateWindowTitle();
    }
}

function saveData() {
    hasUnsavedChanges = true;
    updateWindowTitle();

    // Auto-save if we already have a file handle
    if (currentFileHandle) {
        clearTimeout(autoSaveTimeout);
        autoSaveTimeout = setTimeout(() => {
            saveToFile(currentFileHandle);
        }, 1000); // 1s debounce
    }
}

async function saveToFile(handle) {
    if (!handle) return false;
    try {
        const writable = await handle.createWritable();
        await writable.write(JSON.stringify(appData, null, 2));
        await writable.close();
        hasUnsavedChanges = false;
        currentFileHandle = handle;
        updateWindowTitle();
        return true;
    } catch (err) {
        console.error("Error al guardar:", err);
        return false;
    }
}

function updateWindowTitle() {
    const fileName = currentFileHandle ? currentFileHandle.name : 'Sin título';
    const indicator = hasUnsavedChanges ? '*' : '';
    document.title = `${indicator}${fileName} - Sistema de Gestión Pedagógica`;
}

function getPairRelationshipScore(group, id1, id2, students) {
    if (!group || !group.observations) return 0;
    const pairId = id1 < id2 ? `${id1}_${id2}` : `${id2}_${id1}`;
    
    let score = 0;
    
    const conflictKeywords = ['ignor', 'rechaz', 'pelea', 'discut', 'conflict', 'problem', 'excluy', 'molest', 'enoj', 'tensión', 'tension', 'distanc', 'discrepan'];
    const supportKeywords = ['ayud', 'apoy', 'colabor', 'compañer', 'integr', 'defend', 'resolv', 'solidar', 'felicit', 'destac', 'participa'];
    
    const studentsList = students || group.students || [];
    
    group.observations.forEach(obs => {
        const textLower = obs.text.toLowerCase();
        const hasConflictKw = conflictKeywords.some(kw => textLower.includes(kw));
        const hasSupportKw = supportKeywords.some(kw => textLower.includes(kw));
        
        const s1 = studentsList.find(s => s.id === id1);
        const s2 = studentsList.find(s => s.id === id2);
        if (!s1 || !s2) return;
        
        const isMentioned = (s) => {
            const namesToCheck = [];
            if (s.preferredName && s.preferredName.trim().length >= 2) {
                namesToCheck.push(s.preferredName.trim().toLowerCase());
            }
            const firstFirstName = s.fullName.split(' ')[0].toLowerCase();
            if (firstFirstName.length >= 2) {
                namesToCheck.push(firstFirstName);
            }
            const fullNameLower = s.fullName.toLowerCase();

            return namesToCheck.some(name => {
                const escapedName = name.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
                const namePattern = new RegExp(`\\b${escapedName}\\b`, 'i');
                return namePattern.test(obs.text);
            }) || obs.text.toLowerCase().includes(fullNameLower);
        };
        
        if (isMentioned(s1) && isMentioned(s2)) {
            let isConflict = false;
            if (obs.confirmedConflicts !== undefined) {
                isConflict = obs.confirmedConflicts.includes(pairId);
            } else {
                isConflict = hasConflictKw;
            }

            let isSupport = false;
            if (obs.confirmedSupports !== undefined) {
                isSupport = obs.confirmedSupports.includes(pairId);
            } else {
                isSupport = hasSupportKw && !hasConflictKw;
            }
            
            if (isConflict) {
                score -= 5.0;
            }
            if (isSupport) {
                score += 2.0;
            }
        }
    });
    
    return score;
}
