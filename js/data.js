// Utility Helpers
function escapeHTML(str) {
    if (str === null || str === undefined) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function normalizeText(text) {
    if (!text) return '';
    return text.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

function generateUniqueId() {
    if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
        return crypto.randomUUID();
    }
    return Date.now().toString(36) + Math.random().toString(36).substring(2, 9);
}

function hslToHex(h, s, l) {
    l /= 100;
    const a = s * Math.min(l, 1 - l) / 100;
    const f = n => {
        const k = (n + h / 30) % 12;
        const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
        return Math.round(255 * color).toString(16).padStart(2, '0');
    };
    return `#${f(0)}${f(8)}${f(4)}`;
}

function generateRandomStudentColor() {
    // Generate distinct, vibrant hues with balanced saturation and lightness
    const hue = Math.floor(Math.random() * 360);
    const sat = Math.floor(Math.random() * 25) + 65; // 65% - 90%
    const light = Math.floor(Math.random() * 16) + 42; // 42% - 58%
    return hslToHex(hue, sat, light);
}

function parseDateString(dateStr) {
    if (!dateStr) return new Date(0);
    if (dateStr.includes('/')) {
        const pts = dateStr.split('/');
        if (pts.length === 3) {
            return new Date(parseInt(pts[2], 10), parseInt(pts[1], 10) - 1, parseInt(pts[0], 10));
        }
    } else if (dateStr.includes('-')) {
        const pts = dateStr.split('-');
        if (pts.length === 3) {
            if (pts[0].length === 4) {
                return new Date(parseInt(pts[0], 10), parseInt(pts[1], 10) - 1, parseInt(pts[2], 10));
            } else {
                return new Date(parseInt(pts[2], 10), parseInt(pts[1], 10) - 1, parseInt(pts[0], 10));
            }
        }
    }
    const d = new Date(dateStr);
    return isNaN(d.getTime()) ? new Date(0) : d;
}

